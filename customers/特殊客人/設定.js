// ===== 特殊客人設定檔 =====
// 用記事本打開編輯,存檔時編碼選 UTF-8。不用懂程式,只要改下面兩個反引號 ` ` 中間的文字。
// 每一行是一位特殊客人。開頭是 # 的行是說明,遊戲會略過。
//
// 格式(欄位之間用 ： 隔開):
//   圖片編號：名字：配料(依點單順序,用 、 隔開)：金錢倍率：名聲倍率
//
//   圖片編號 = 這個資料夾裡的圖片檔名,1 代表 1.png
//   名字     = 上菜時頭上會顯示「★特殊客人・名字」,可以空白
//   配料     = 這位客人「固定」點的配料,順序也固定,要依序放才算「非常完美」
//              可用:葱花、海苔、溏心蛋、叉燒、筍乾、花花、玉米、炙燒五花、豆芽、辣味噌
//              同一種可以重複寫,例如:溏心蛋、溏心蛋、叉燒
//   金錢倍率 = 上菜收入乘幾倍,不寫就是 2
//   名聲倍率 = 名聲(升級用)乘幾倍,不寫就跟金錢倍率一樣
//
// 注意:
//   - 所有配料都解鎖之前(目前是等級 7 之前),特殊客人點單跟一般客人一樣隨機,
//     收入和名聲固定 ×2。全部配料解鎖後才會照這個檔案的固定點單和倍率。
//   - 特殊客人出現機率看下面的 JNR_SPECIAL_RATE(0.25 = 每 4 位客人約 1 位)。演示模式固定出現 2 位。
//   - 編號要有對應的圖片才會生效。
// 特殊客人出現機率:0.25 = 25%。想更常出現就調高(最高 1),想少一點就調低,例如 0.1。
window.JNR_SPECIAL_RATE=0.25;

// 圖片放大倍率(只有「直接雙擊開 html」時才會用到)。你的圖是像素原圖放大 3 倍存檔就維持 3,
// 放大 4 倍就改 4。用 GitHub 網址玩時遊戲會自動偵測,不受這個影響。
window.JNR_UPSCALE=3;

window.JNR_SPECIAL=`
# 下面五位是範例點單(都只用等級 1 就有的配料,前期就會出現),請改成你想要的
1：：海苔、溏心蛋、葱花：2：2
2：：葱花、溏心蛋：2：2
3：：溏心蛋、溏心蛋、海苔：2：2
4：：葱花、海苔、溏心蛋：3：3
5：：海苔、海苔、溏心蛋、葱花：4：4
`;
